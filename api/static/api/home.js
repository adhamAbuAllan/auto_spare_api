const rtlLanguages = new Set(["ar", "he"]);
const defaultLanguage = "en";

function storedLanguage() {
    try {
        return localStorage.getItem("autoSpareLanguage");
    } catch (error) {
        return null;
    }
}

function saveLanguage(language) {
    try {
        localStorage.setItem("autoSpareLanguage", language);
    } catch (error) {
        return;
    }
}

function browserLanguage() {
    const language = (navigator.language || "").slice(0, 2).toLowerCase();
    return translations[language] ? language : defaultLanguage;
}

function applyLanguage(language) {
    const nextLanguage = translations[language] ? language : defaultLanguage;
    const copy = translations[nextLanguage];
    const fallback = translations[defaultLanguage];
    const direction = rtlLanguages.has(nextLanguage) ? "rtl" : "ltr";

    document.documentElement.lang = nextLanguage;
    document.documentElement.dir = direction;
    document.body.dataset.lang = nextLanguage;
    document.title = copy.metaTitle;

    const description = document.querySelector('meta[name="description"]');
    if (description) {
        description.setAttribute("content", copy.metaDescription);
    }

    document.querySelectorAll("[data-i18n]").forEach((element) => {
        const key = element.dataset.i18n;
        element.textContent = copy[key] || fallback[key] || "";
    });

    document.querySelectorAll("[data-lang]").forEach((button) => {
        const isCurrent = button.dataset.lang === nextLanguage;
        button.setAttribute("aria-pressed", String(isCurrent));
    });

    saveLanguage(nextLanguage);
}

document.querySelectorAll("[data-lang]").forEach((button) => {
    button.addEventListener("click", () => {
        applyLanguage(button.dataset.lang);
    });
});

applyLanguage(storedLanguage() || browserLanguage());
